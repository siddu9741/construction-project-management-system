function applySavedAppLanguage() {
  let selectedLanguage = "en";

  try {
    const savedLanguage = localStorage.getItem(APP_LANGUAGE_KEY);
    if (appTranslations[savedLanguage]) {
      selectedLanguage = savedLanguage;
    }
  } catch (error) {
    // If browser storage is unavailable, use English.
  }

  document.documentElement.lang = selectedLanguage;
  const words = appTranslations[selectedLanguage];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = words[element.dataset.i18n];
    if (translation) {
      element.textContent = translation;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const translation = words[element.dataset.i18nPlaceholder];
    if (translation) {
      element.placeholder = translation;
    }
  });
}

